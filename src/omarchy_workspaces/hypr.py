"""Hyprland IPC and version-aware generation. No compositor callback blocks."""
import json
from itertools import permutations
import re
import shlex
import subprocess
from pathlib import Path

from .core import Error, binding_shortcut, key_identity, quote


class Hypr:
    def call(self, *args):
        try:
            result = subprocess.run(["hyprctl", *args], capture_output=True, text=True, timeout=10)
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise Error(f"无法连接 Hyprland：{exc}") from exc
        if result.returncode:
            raise Error(result.stderr.strip() or result.stdout.strip() or "hyprctl 失败")
        return result.stdout.strip()

    def query(self, name):
        try:
            return json.loads(self.call("-j", name))
        except ValueError as exc:
            raise Error(f"hyprctl {name} 未返回有效 JSON") from exc

    def dispatch(self, expression, *legacy):
        try:
            output = self.call("dispatch", expression)
            if output.lower() not in ("ok", ""):
                raise Error(output)
        except Error:
            output = self.call("dispatch", *legacy)
            if output.lower() not in ("ok", ""):
                raise Error(output)

    def focus(self, client):
        address = checked_address(client)
        self.dispatch(f"hl.dsp.focus({{ window = {quote('address:' + address)} }})", "focuswindow", f"address:{address}")

    def move(self, client, workspace):
        address = checked_address(client)
        self.dispatch(f"hl.dsp.window.move({{ window = {quote('address:' + address)}, workspace = {quote(str(workspace))}, follow = false }})", "movetoworkspacesilent", f"{workspace},address:{address}")

    def visible_scratchpad(self):
        monitors = self.query("monitors")
        focused = next((m for m in monitors if m.get("focused")), None)
        if not focused:
            return None
        special = focused.get("specialWorkspace") or {}
        if special.get("name") == "special:scratchpad" and special.get("id", 0) < 0:
            return "special:scratchpad"
        return None

    def reload(self):
        result = self.call("reload")
        if result.lower() not in ("ok", ""):
            raise Error(result)
        errors = self.call("configerrors")
        if errors not in ("", "[]"):
            raise Error(f"Hyprland 配置错误：{errors}")


def checked_address(client):
    address = client.get("address", "")
    if not re.fullmatch(r"0x[0-9a-fA-F]+", address):
        raise Error("窗口地址无效")
    return address


def detect(paths, config, hypr):
    defaults = config["defaults"]
    version = hypr.query("version")
    match = re.search(r"(?:v)?(\d+)\.(\d+)", version.get("version", ""))
    if not match:
        raise Error("无法识别 Hyprland 版本，请运行 omarchy-workspaces doctor")
    number = tuple(map(int, match.groups()))
    backend = defaults.get("backend", "auto")
    if backend == "auto":
        backend = "lua" if number >= (0, 55) else "conf" if number >= (0, 53) else "v2"
    if backend == "lua" and number < (0, 55):
        raise Error("Lua 后端需要 Hyprland 0.55+")
    main = Path(defaults.get("hypr_config", paths.config / ("hypr/hyprland.lua" if backend == "lua" else "hypr/hyprland.conf"))).expanduser()
    if not main.is_file():
        raise Error(f"找不到配置入口 {main}；自定义启动配置请设置 defaults.hypr_config")
    return backend, main


def literal(value):
    return "^" + re.sub(r"([\\.\[\](){}*+?^$|])", r"\\\1", value) + "$"


def lua_unbind_variants(key):
    # Lua unbind compares the original combo string, including modifier order.
    # IPC retains the keysym but only exposes a numeric modifier mask.
    parts = key.split(" + ")
    mods, symbol = parts[:-1], parts[-1]
    symbols = {symbol, symbol.upper(), symbol.lower()}
    return {" + ".join((*order, sym)) for order in permutations(mods) for sym in symbols}


def generate(config, backend, binary, binds):
    prefix = "--" if backend == "lua" else "#"
    lines = [f"{prefix} Generated by omarchy-workspaces; edit apps.toml instead."]
    entries = sorted([(len(m), app_id, m, app["workspace"]) for app_id, app in config["apps"].items() for m in app["matches"]], key=lambda x: (x[0], x[1]))
    for i, (_, app_id, match, workspace) in enumerate(entries):
        if backend == "lua":
            props = ", ".join(f"{k} = {quote(literal(v))}" for k, v in match.items()) + ', workspace = "s[false]"'
            lines.append(f"hl.window_rule({{ name = {quote(f'ows-{app_id}-{i}')}, match = {{ {props} }}, workspace = {quote(str(workspace) + ' silent')} }})")
        elif backend == "conf":
            lines.extend(["windowrule {", f"  name = ows-{app_id}-{i}"])
            lines.extend(f"  match:{k} = {conf_literal(v)}" for k, v in match.items())
            lines.extend(["  match:workspace = s[false]", f"  workspace = {workspace} silent", "}"])
        else:
            old = {"class": "class", "initial_class": "initialclass", "initial_title": "initialtitle"}
            props = ",".join(f"{old[k]}:{conf_literal(v)}" for k, v in match.items())
            lines.append(f"windowrulev2 = workspace {workspace} silent,{props},onworkspace:s[false]")
    replacements = []
    for app_id, app in config["apps"].items():
        for key in app.get("shortcuts", []):
            existing = [b for b in binds if binding_shortcut(b) and key_identity(binding_shortcut(b)) == key_identity(key)]
            for b in existing:
                ours = (str(binary) in str(b.get("arg", "")) and " launch " in str(b.get("arg", ""))) or (
                    backend == 'lua' and b.get('dispatcher') == '__lua'
                    and b.get('description') == '工作区: ' + app.get('name', app_id))
                if not ours and not app.get("replace_shortcuts", False):
                    raise Error(f"{key} 已绑定 {b.get('description') or b.get('arg')}；确认要替换时使用 --replace-shortcut")
                if not ours:
                    replacements.append(f"{key}: {b.get('description') or b.get('arg')} -> {app.get('name', app_id)}")
            command = shlex.join([str(binary), "launch", app_id])
            if backend == "lua":
                actual = set().union(*(lua_unbind_variants(k) for k in ({key} | {binding_shortcut(b) for b in existing})))
                for old_key in sorted(actual):
                    lines.append(f"hl.unbind({quote(old_key)})")
                lines.append(f"hl.bind({quote(key)}, hl.dsp.exec_cmd({quote(command)}), {{ description = {quote('工作区: ' + app.get('name', app_id))} }})")
            else:
                parts = key.split(" + ")
                mods, sym = " ".join(parts[:-1]), parts[-1]
                lines.extend([f"unbind = {mods}, {sym}", f"bindd = {mods}, {sym}, 工作区: {app.get('name', app_id)}, exec, {command}"])
    return "\n".join(lines) + "\n", replacements


def conf_literal(value):
    # Hyprlang strips comments and commas are delimiters in v2. Lua has no such limitation.
    if any(c in value for c in "#,{=} "):
        raise Error("旧版 Hyprland 的匹配值含特殊字符，请升级或使用不含特殊字符的应用身份")
    return literal(value)
